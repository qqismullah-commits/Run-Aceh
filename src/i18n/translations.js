export function t(lang, key, vars = {}) {
  const dict = I18N[lang] || I18N.id;
  let template = dict[key] ?? I18N.id[key] ?? key;
  for (const [varKey, varVal] of Object.entries(vars)) {
    template = template.replaceAll(`{${varKey}}`, String(varVal));
  }
  return template;
}
